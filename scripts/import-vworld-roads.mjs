#!/usr/bin/env node
/**
 * Imports road centerlines for a Seoul bounding box from VWorld (브이월드)
 * and writes an SQL file that upserts them into the Supabase `roads` table.
 *
 * Run on your own machine (needs network access to api.vworld.kr):
 *
 *   VWORLD_API_KEY=your-key npm run import:roads
 *
 * Optional environment variables:
 *   VWORLD_DOMAIN   domain registered with the key, if the key requires one
 *   BBOX            "minLon,minLat,maxLon,maxLat" (default: City Hall area)
 *   MAX_FEATURES    upper bound per request (default: 1000)
 *   OUT             output path (default: supabase/seed-roads.sql)
 *
 * Layer: lt_l_n3a0020000 (도로 중심선). Attributes used:
 *   ufid   stable id          rdnm   road name
 *   rvwd   road width (m)     (default width 8 m when missing)
 */

import { writeFile } from 'node:fs/promises';

const LAYER = 'lt_l_n3a0020000';
const ID_FIELD = 'ufid';
const NAME_FIELD = 'rdnm';
const WIDTH_FIELD = 'rvwd';
const DEFAULT_WIDTH = 8;

const env = process.env;
const apiKey = env.VWORLD_API_KEY;
if (!apiKey) {
  console.error('VWORLD_API_KEY is required. Use the same key as the buildings import.');
  process.exit(1);
}

const [minLon, minLat, maxLon, maxLat] = (env.BBOX ?? '126.970,37.560,126.990,37.572')
  .split(',')
  .map(Number);
if ([minLon, minLat, maxLon, maxLat].some(Number.isNaN)) {
  console.error('BBOX must be "minLon,minLat,maxLon,maxLat".');
  process.exit(1);
}

const MAX_FEATURES = Number(env.MAX_FEATURES ?? 1000);
const OUT = env.OUT ?? 'supabase/seed-roads.sql';

// Same local meter frame as the buildings import (origin: Seoul City Hall, x east, z south).
const ORIGIN_LON = 126.978;
const ORIGIN_LAT = 37.5665;
const METERS_PER_DEG_LAT = 110_540;
const METERS_PER_DEG_LON = 111_320 * Math.cos((ORIGIN_LAT * Math.PI) / 180);

const round = (value) => Math.round(value * 100) / 100;
const project = ([lon, lat]) => [
  round((lon - ORIGIN_LON) * METERS_PER_DEG_LON),
  round(-(lat - ORIGIN_LAT) * METERS_PER_DEG_LAT),
];
const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;

async function fetchFeatures(bboxValue) {
  const params = new URLSearchParams({
    service: 'WFS',
    version: '1.1.0',
    request: 'GetFeature',
    typename: LAYER,
    srsName: 'EPSG:4326',
    output: 'application/json',
    bbox: bboxValue,
    maxFeatures: String(MAX_FEATURES),
    key: apiKey,
  });
  if (env.VWORLD_DOMAIN) params.set('domain', env.VWORLD_DOMAIN);

  const response = await fetch(`https://api.vworld.kr/req/wfs?${params}`);
  const text = await response.text();

  // VWorld returns XML error documents, so parse and check the body, not only the status.
  let json;
  try {
    json = JSON.parse(text);
  } catch {
    throw new Error(`Expected GeoJSON from VWorld but got:\n${text.slice(0, 400)}`);
  }
  if (!response.ok) throw new Error(`HTTP ${response.status}: ${text.slice(0, 400)}`);

  return json.features ?? [];
}

/** Each feature can hold several polylines. Return one lon/lat array per polyline. */
function polylines(geometry) {
  if (!geometry) return [];
  if (geometry.type === 'LineString') return [geometry.coordinates];
  if (geometry.type === 'MultiLineString') return geometry.coordinates;
  return [];
}

function toRows(feature, index) {
  const props = feature.properties ?? {};
  const rawId = props[ID_FIELD] ?? feature.id ?? `row-${index}`;
  const rawWidth = Number(props[WIDTH_FIELD]);
  const width = rawWidth > 0 ? round(rawWidth) : DEFAULT_WIDTH;
  const name = props[NAME_FIELD] || '';

  return polylines(feature.geometry)
    .filter((line) => line.length >= 2)
    .map((line, part) => ({
      id: `road-${rawId}-${part}`,
      name,
      width,
      points: line.map(project),
    }));
}

function toSql(rows) {
  const header = [
    `-- Generated by scripts/import-vworld-roads.mjs from VWorld layer ${LAYER}`,
    `-- BBOX ${minLon},${minLat},${maxLon},${maxLat}; ${rows.length} road polylines`,
    '',
  ];
  const values = rows.map(
    (r) =>
      `(${[
        sqlString(r.id),
        sqlString(r.name),
        r.width,
        `${sqlString(JSON.stringify(r.points))}::jsonb`,
      ].join(', ')})`,
  );
  return [
    ...header,
    'insert into public.roads (id, name, width, points) values',
    values.join(',\n'),
    'on conflict (id) do update set',
    '  name = excluded.name, width = excluded.width, points = excluded.points;',
    '',
  ].join('\n');
}

// EPSG:4326 is lat/lon axis order in WFS 1.1.0 per the OGC spec, but some servers
// expect lon/lat. Try lon,lat first, then lat,lon if nothing comes back.
const BBOX_LONLAT = `${minLon},${minLat},${maxLon},${maxLat},EPSG:4326`;
const BBOX_LATLON = `${minLat},${minLon},${maxLat},${maxLon},EPSG:4326`;

let features = await fetchFeatures(BBOX_LONLAT);
if (features.length === 0) {
  console.warn('0 features with lon,lat bbox order. Retrying with lat,lon order...');
  features = await fetchFeatures(BBOX_LATLON);
  if (features.length > 0) console.log('lat,lon order worked. Consider keeping it as the default.');
}
console.log(`Received ${features.length} features from ${LAYER}`);
if (features.length >= MAX_FEATURES) {
  console.warn(`Hit MAX_FEATURES=${MAX_FEATURES}. Narrow BBOX or raise MAX_FEATURES to get the rest.`);
}

const rows = features.flatMap(toRows);
if (rows.length === 0) {
  console.error('No road lines to write. Check BBOX and the layer name.');
  process.exit(1);
}

await writeFile(OUT, toSql(rows), 'utf8');
console.log(`Wrote ${rows.length} road polylines to ${OUT}`);
console.log('Next: run supabase/schema.sql once (for the roads table), then paste this file in the SQL editor.');
